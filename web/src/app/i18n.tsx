interface I18nContextValue {
  language: Language;
  locale: string;
  setLanguage(language: Language): void;
  t: Translate;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function initialLanguage(): Language {
  try {
    const stored = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (stored === 'en' || stored === 'zh-CN') return stored;
  } catch {
    // The UI remains usable when persistent storage is unavailable.
  }
  return navigator.languages.some((language) => language.toLowerCase().startsWith('zh'))
    ? 'zh-CN'
    : 'en';
}

function interpolate(message: string, values?: TranslationValues): string {
  if (!values) return message;
  return message.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : match);
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage);
  const setLanguage = useCallback((next: Language) => {
    setLanguageState(next);
    try {
      window.localStorage.setItem(LANGUAGE_STORAGE_KEY, next);
    } catch {
      // A language change still applies for the current page without storage.
    }
  }, []);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const t = useCallback<Translate>((message, values) => {
    const translated = language === 'zh-CN' ? (zhCN[message] ?? message) : message;
    return interpolate(translated, values);
  }, [language]);

  const value = useMemo<I18nContextValue>(() => ({
    language,
    locale: language === 'zh-CN' ? 'zh-CN' : 'en-US',
    setLanguage,
    t,
  }), [language, setLanguage, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('i18n_provider_missing');
  return value;
}
